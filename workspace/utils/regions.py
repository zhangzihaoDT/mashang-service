"""
大区架构归一工具函数

统一旧架构（一区/二区/三区-*）→ 新架构（东区/西区/北区-*）的映射与归一逻辑。
原散落于 launch_cumulative_lock_compare.py / l6_m2_presale_report.py 的重复定义，
收敛至本模块，避免第三份复制。
"""

import pandas as pd

# 大区架构归一：DM0/DM1 预售期为旧架构（一区/二区/三区-*），DM2 为新架构（东区/西区/北区-*）。
# 按省份组后缀映射到新架构；未命中时保留原名。
REGION_MAP_OLD_TO_NEW = {
    "一区-苏皖": "东区-江苏",
    "一区-浙江": "东区-浙江",
    "一区-闽赣": "东区-闽赣",
    "一区-鲁豫": "东区-鲁豫",
    "二区-鄂桂湘": "华中区",
    "二区-川云": "西区-川云",
    "二区-贵渝": "西区-贵渝",
    "三区-京津东北": "北区-京津东北",
    "三区-山河": "北区-山河",
    "三区-西北": "北区-西北",
    "上海区": "上海区",
    "华南特区": "华南特区",
    "虚拟大区": "虚拟大区",
}


def norm_region(name) -> str:
    """大区命名归一：空值（含 NA）→ 未知；旧架构（一区/二区/三区-*）→ 新架构（东/西/北区-*）。"""
    if name is None or pd.isna(name) or str(name).strip() == "":
        return "未知"
    return REGION_MAP_OLD_TO_NEW.get(str(name).strip(), str(name).strip())
